// Generates src/lib/api/types.gen.ts from orbit-be's swagger.json.
// Usage: node scripts/gen-api-types.mjs [path/to/swagger.json]
import { readFile, writeFile } from "node:fs/promises";

const source = process.argv[2] ?? "../orbit-be/docs/swagger.json";
const out = "src/lib/api/types.gen.ts";
const swagger = JSON.parse(await readFile(source, "utf8"));
const defs = swagger.definitions ?? {};

const shortName = (full) => {
  const list = /\.ListResponse-(.+)$/.exec(full);
  if (list) return `ListResponse<${shortName(list[1].replace(/_([A-Za-z0-9]+)$/, ".$1"))}>`;
  return full.split(".").pop();
};

const refName = (ref) => shortName(ref.replace("#/definitions/", ""));

const typeOf = (schema) => {
  if (!schema) return "unknown";
  if (schema.$ref) return refName(schema.$ref);
  if (schema.allOf) return schema.allOf.map(typeOf).join(" & ");
  if (schema.enum) return schema.enum.map((v) => JSON.stringify(v)).join(" | ");
  switch (schema.type) {
    case "string":
      return "string";
    case "integer":
    case "number":
      return "number";
    case "boolean":
      return "boolean";
    case "array":
      return `${wrap(typeOf(schema.items))}[]`;
    case "object":
      if (schema.properties) return inline(schema);
      if (schema.additionalProperties) return `Record<string, ${typeOf(schema.additionalProperties)}>`;
      return "Record<string, unknown>";
    default:
      return "unknown";
  }
};

const wrap = (t) => (/[|&]/.test(t) ? `(${t})` : t);

const inline = (schema) => {
  const req = new Set(schema.required ?? []);
  const body = Object.entries(schema.properties ?? {})
    .map(([k, v]) => `${JSON.stringify(k).replace(/^"([a-z_][a-z0-9_]*)"$/i, "$1")}${req.has(k) ? "" : "?"}: ${typeOf(v)}${req.has(k) ? "" : " | null"}`)
    .join("; ");
  return `{ ${body} }`;
};

const lines = [
  "// Generated by scripts/gen-api-types.mjs from orbit-be's swagger.json. Do not edit by hand.",
  "",
  "export interface ListResponse<T> { items: T[]; total: number; page: number; page_size: number }",
  "",
];

const seen = new Map();
for (const [full, schema] of Object.entries(defs).sort(([a], [b]) => shortName(a).localeCompare(shortName(b)))) {
  if (full.includes(".ListResponse-")) continue;
  const name = shortName(full);
  if (seen.has(name)) throw new Error(`Two definitions shorten to ${name}: ${seen.get(name)} and ${full}`);
  seen.set(name, full);
  if (schema.type === "object" || schema.properties) {
    const req = new Set(schema.required ?? []);
    const props = Object.entries(schema.properties ?? {}).map(([k, v]) => {
      const optional = !req.has(k);
      const doc = v.description ? `  /** ${v.description.replace(/\*\//g, "*\\/")} */\n` : "";
      return `${doc}  ${k}${optional ? "?" : ""}: ${typeOf(v)}${optional ? " | null" : ""};`;
    });
    lines.push(`export interface ${name} {`, ...props, "}", "");
  } else {
    lines.push(`export type ${name} = ${typeOf(schema)};`, "");
  }
}

await writeFile(out, lines.join("\n"));
console.log(`wrote ${out}: ${seen.size} types from ${source}`);
